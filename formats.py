"""Session-format index. Stdlib only. No store walk.

prefix is the engine PREFIX value. An id is that prefix, a hyphen, and the
vendor id. load is measured, unmeasured, or absent. resume is an argv shape,
OPENWORK_FOCUS, UNMEASURED, or POINTER. A found binary replaces argv[0] only.
"""
from __future__ import annotations

SCHEMA = "cmsessions-format-index/1"

_KEYS = (
    "harness", "prefix", "title", "home", "header",
    "title_fields", "body", "load", "resume", "notes",
)


def _rec(
    harness: str,
    prefix: str | None,
    title: str | None,
    home: str | None,
    header: str | None,
    title_fields: str | None,
    body: str | None,
    load: str,
    resume: str,
    notes: str | None,
) -> dict:
    row = {
        "harness": harness,
        "prefix": prefix,
        "title": title,
        "home": home,
        "header": header,
        "title_fields": title_fields,
        "body": body,
        "load": load,
        "resume": resume,
        "notes": notes,
    }
    if tuple(row) != _KEYS:
        raise RuntimeError("format record keys drifted")
    return row


